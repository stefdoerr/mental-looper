// 5x7 bitmap font for the loop widget: 0-9 : - T R E C D U B P L A Y S O M and space; 3x5 digits for the counts.
#pragma once
#include <cstddef>
#include <cstdint>

namespace ouro {

// Mono1 bit access (rows top->bottom, (w+7)/8 bytes per row, MSB = leftmost). Clips to w only; callers keep y in range.
inline void setPixel(uint8_t* bits, uint16_t w, int x, int y)
{
    if (x >= 0 && x < w && y >= 0) bits[y * ((w + 7) / 8) + x / 8] |= uint8_t(0x80 >> (x % 8));
}

// Rows of 5 bits each (bit 4 = leftmost); unknown characters draw as space.
inline const uint8_t* glyph(char c)
{
    static const struct { char c; uint8_t r[7]; } g[] = {
        {'0', {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}}, {'1', {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E}},
        {'2', {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}}, {'3', {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E}},
        {'4', {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}}, {'5', {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E}},
        {'6', {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}}, {'7', {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}},
        {'8', {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}}, {'9', {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C}},
        {':', {0x00, 0x04, 0x00, 0x00, 0x00, 0x04, 0x00}}, {'-', {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00}},
        {'T', {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}}, {'R', {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11}},
        {'E', {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F}}, {'C', {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E}},
        {'D', {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E}}, {'U', {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}},
        {'B', {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E}}, {'P', {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10}},
        {'L', {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F}}, {'A', {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}},
        {'Y', {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04}}, {'S', {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}},
        {'O', {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}}, {'M', {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}},
    };
    static const uint8_t blank[7] = {};
    for (const auto& e : g) if (e.c == c) return e.r;
    return blank;
}

// Track-mark glyphs: 5x5 symbols centred in the 7x7 mark cell (blank outer ring, so the selection frame never touches them),
// rows of 7 bits each (bit 6 = leftmost): cassette-player transport symbols.
static const uint8_t kMarkDisc[7] = { 0x00, 0x1C, 0x3E, 0x3E, 0x3E, 0x1C, 0x00 };   // record / overdub
static const uint8_t kMarkPlay[7] = { 0x00, 0x10, 0x18, 0x1C, 0x18, 0x10, 0x00 };   // playing, on (3 px wide, centred)
static const uint8_t kMarkStop[7] = { 0x00, 0x3E, 0x3E, 0x3E, 0x3E, 0x3E, 0x00 };   // playing, muted

// 3x5 digits for the per-track layer counts: rows of 3 bits each (bit 2 = leftmost).
static const uint8_t kDigits3x5[10][5] = {
    {7, 5, 5, 5, 7}, {2, 6, 2, 2, 7}, {7, 1, 7, 4, 7}, {7, 1, 7, 1, 7}, {5, 5, 7, 1, 1},
    {7, 4, 7, 1, 7}, {7, 4, 7, 5, 7}, {7, 1, 1, 1, 1}, {7, 5, 7, 5, 7}, {7, 5, 7, 1, 7},
};

// ORs n in 3x5 digits centred in the 7 px wide cell at x, top at y: two digits 1 px apart fill it, one takes the middle
// 3 columns. Above 99 draws 99.
inline void drawCount(uint8_t* bits, uint16_t w, int x, int y, uint32_t n)
{
    if (n > 99) n = 99;
    const auto digit = [&](int dx, uint32_t d) {
        for (int r = 0; r < 5; ++r)
            for (int c = 0; c < 3; ++c)
                if (kDigits3x5[d][r] & (0x4 >> c)) setPixel(bits, w, x + dx + c, y + r);
    };
    if (n < 10) digit(2, n);
    else { digit(0, n / 10); digit(4, n % 10); }
}

// ORs the text into bits (width w) with its top-left at x,y; 6 px per character.
inline void drawText(uint8_t* bits, uint16_t w, int x, int y, const char* s)
{
    for (; *s != '\0'; ++s, x += 6)
    {
        const uint8_t* r = glyph(*s);
        for (int row = 0; row < 7; ++row)
            for (int col = 0; col < 5; ++col)
                if (r[row] & (0x10 >> col)) setPixel(bits, w, x + col, y + row);
    }
}

} // namespace ouro
